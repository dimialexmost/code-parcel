import * as crypto from 'crypto';
import * as fs from 'fs/promises';
import { constants as fsConstants, type Stats } from 'fs';
import * as path from 'path';
import { TextDecoder } from 'util';
import { validateOutputDirectory } from './config';
import { FileScanner } from './file-scanner';
import { SelectionStore } from './selection-store';
import { getWorkspaceRelativeOutputPath, isMandatoryExcludedPath, normalizeRelativePath, resolveOutputDirectory, validateOutputFilename } from './utils';

export interface SkippedFile {
    relativePath: string;
    reason: 'binary' | 'too_large' | 'unreadable' | 'unsupported';
}

export interface SnapshotGenerationResult {
    outputPath: string;
    includedFiles: number;
    skippedFiles: SkippedFile[];
}

interface IncludedFile {
    relativePath: string;
    content: string;
    language: string;
}

interface GenerationLockMetadata {
    version: 1;
    pid: number;
    workspaceId: string;
    token: string;
    createdAt: number;
}

interface LockFileIdentity {
    dev: number;
    ino: number;
    size: number;
    birthtimeMs: number;
    ctimeMs: number;
    mtimeMs: number;
}

interface InspectedGenerationLock {
    metadata: GenerationLockMetadata;
    identity: LockFileIdentity;
}

const GENERATOR_MARKER = '<!-- Generated by Code Parcel -->';
const MAX_SNAPSHOT_SIZE_BYTES = 50 * 1024 * 1024;
const activeRoots = new Set<string>();

const LANGUAGE_BY_EXTENSION: Record<string, string> = {
    '.ts': 'typescript', '.tsx': 'typescript', '.js': 'javascript', '.jsx': 'javascript', '.mjs': 'javascript',
    '.cjs': 'javascript', '.php': 'php', '.py': 'python', '.java': 'java', '.html': 'html', '.htm': 'html',
    '.css': 'css', '.scss': 'scss', '.json': 'json', '.xml': 'xml', '.yml': 'yaml', '.yaml': 'yaml',
    '.md': 'markdown', '.txt': 'text', '.sql': 'sql', '.ps1': 'powershell', '.sh': 'bash', '.bash': 'bash',
    '.bat': 'bat', '.cmd': 'bat'
};

export class SnapshotGenerator {
    private readonly root: string;

    constructor(workspaceRoot: string, private readonly store: SelectionStore, private readonly scanner: FileScanner) {
        this.root = path.resolve(workspaceRoot);
    }

    async generate(): Promise<SnapshotGenerationResult> {
        const rootKey = process.platform === 'win32' ? this.root.toLowerCase() : this.root;
        if (activeRoots.has(rootKey)) throw new Error('Snapshot generation is already in progress for this workspace.');
        activeRoots.add(rootKey);
        let temporaryPath: string | undefined;
        let lockPath: string | undefined;
        let lockCreated = false;
        let lockMetadata: GenerationLockMetadata | undefined;
        let lockIdentity: LockFileIdentity | undefined;
        try {
            await this.store.ensureWorkspaceIdentityPersisted();
            const config = this.store.getConfig();
            validateOutputFilename(config.outputFile);
            validateOutputDirectory(config.outputDirectory);
            const destination = resolveOutputDirectory(this.root, config.outputDirectory);
            await validateDestinationDirectory(destination);
            const outputPath = path.resolve(destination, config.outputFile);
            if (path.dirname(outputPath) !== destination) throw new Error('The snapshot filename must remain inside its destination folder.');
            const outputRelativePath = getWorkspaceRelativeOutputPath(this.root, config.outputFile, config.outputDirectory);
            this.scanner.setOutputFile(outputRelativePath);
            const ownerId = config.workspaceId;

            lockPath = `${outputPath}.code-parcel.lock`;
            lockMetadata = {
                version: 1,
                pid: process.pid,
                workspaceId: ownerId,
                token: crypto.randomUUID(),
                createdAt: Date.now()
            };
            lockIdentity = await acquireGenerationLock(lockPath, lockMetadata, destination);
            lockCreated = true;

            const included: IncludedFile[] = [];
            const skippedFiles: SkippedFile[] = [];
            let estimatedSnapshotBytes = 1024 + Buffer.byteLength(path.basename(this.root), 'utf8');
            const estimatedDirectories = new Set<string>();
            const recordSkipped = (relativePath: string, reason: SkippedFile['reason']): void => {
                skippedFiles.push({ relativePath, reason });
                estimatedSnapshotBytes += Buffer.byteLength(`- ${escapeMarkdownPath(relativePath)} \u2014 ${reason}\n`, 'utf8');
                assertSnapshotSize(estimatedSnapshotBytes);
            };
            for await (const entry of this.scanner.enumerateFiles('', directory => this.store.shouldScanDirectory(directory))) {
                if (entry.type === 'symlink' || entry.type === 'other') {
                    if (this.store.isIncluded(entry.relativePath)) {
                        recordSkipped(entry.relativePath, 'unsupported');
                    }
                    continue;
                }
                if (entry.type !== 'file' || isMandatoryExcludedPath(entry.relativePath, outputRelativePath) ||
                    !this.store.isIncluded(entry.relativePath)) continue;

                let size: number;
                try {
                    const stat = await fs.lstat(entry.absolutePath);
                    if (!stat.isFile()) {
                        recordSkipped(entry.relativePath, 'unsupported');
                        continue;
                    }
                    size = stat.size;
                } catch {
                    recordSkipped(entry.relativePath, 'unreadable');
                    continue;
                }
                if (size > config.maxFileSizeBytes) {
                    recordSkipped(entry.relativePath, 'too_large');
                    continue;
                }

                let bytes: Buffer;
                try {
                    bytes = await fs.readFile(entry.absolutePath);
                } catch {
                    recordSkipped(entry.relativePath, 'unreadable');
                    continue;
                }
                if (bytes.byteLength > config.maxFileSizeBytes) {
                    recordSkipped(entry.relativePath, 'too_large');
                    continue;
                }
                const decoded = decodeText(bytes);
                if (decoded === undefined) {
                    recordSkipped(entry.relativePath, 'binary');
                    continue;
                }
                if (decoded.startsWith(GENERATOR_MARKER)) continue;
                const relativePath = normalizeRelativePath(entry.relativePath);
                const file = {
                    relativePath,
                    content: decoded,
                    language: LANGUAGE_BY_EXTENSION[path.extname(entry.name).toLowerCase()] ?? ''
                };
                estimatedSnapshotBytes += estimateIncludedFileBytes(file, included.length > 0, estimatedDirectories);
                assertSnapshotSize(estimatedSnapshotBytes);
                included.push(file);
            }

            included.sort((a, b) => compareRelativePaths(a.relativePath, b.relativePath));
            skippedFiles.sort((a, b) => compareRelativePaths(a.relativePath, b.relativePath));
            const markdown = buildMarkdown(path.basename(this.root), ownerId, included, skippedFiles);
            assertSnapshotSize(Buffer.byteLength(markdown, 'utf8'));

            await assertSafeExistingOutput(outputPath, ownerId);
            temporaryPath = path.join(destination, `${config.outputFile}.${process.pid}.${crypto.randomUUID()}.tmp`);
            try {
                await fs.writeFile(temporaryPath, markdown, { encoding: 'utf8', flag: 'wx' });
            } catch (error) {
                throw new Error(`Could not write the snapshot in ${destination}: ${errorMessage(error)}`);
            }
            await assertSafeExistingOutput(outputPath, ownerId);
            try {
                // fs.rename uses the platform's replace operation; on Windows a locked/unsafe target
                // fails without deleting the previous file, so no delete-then-rename fallback is used.
                await fs.rename(temporaryPath, outputPath);
                temporaryPath = undefined;
            } catch (error) {
                throw new Error(`Could not safely replace the snapshot file: ${errorMessage(error)}`);
            }

            return { outputPath, includedFiles: included.length, skippedFiles };
        } finally {
            if (temporaryPath) {
                try { await fs.unlink(temporaryPath); } catch { /* Best-effort cleanup after a failed write. */ }
            }
            if (lockCreated && lockPath && lockMetadata && lockIdentity) {
                await releaseGenerationLock(lockPath, lockMetadata, lockIdentity);
            }
            activeRoots.delete(rootKey);
        }
    }
}

function decodeText(bytes: Buffer): string | undefined {
    if (hasBinarySignature(bytes)) return undefined;
    let encoding = 'utf-8';
    let payload = bytes;
    if (bytes.length >= 3 && bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf) {
        payload = bytes.subarray(3);
    } else if (bytes.length >= 2 && bytes[0] === 0xff && bytes[1] === 0xfe) {
        encoding = 'utf-16le';
        payload = bytes.subarray(2);
    } else if (bytes.length >= 2 && bytes[0] === 0xfe && bytes[1] === 0xff) {
        encoding = 'utf-16be';
        payload = bytes.subarray(2);
    }
    if (encoding === 'utf-8' && payload.includes(0)) return undefined;
    try {
        const text = new TextDecoder(encoding, { fatal: true }).decode(payload);
        if (text.includes('\0')) return undefined;
        let suspicious = 0;
        for (const character of text.slice(0, 8192)) {
            const code = character.charCodeAt(0);
            if ((code < 0x20 && code !== 0x09 && code !== 0x0a && code !== 0x0d && code !== 0x0c) || code === 0x7f) suspicious++;
        }
        const sampleLength = Math.min(text.length, 8192);
        if (sampleLength > 0 && suspicious / sampleLength > 0.02) return undefined;
        return text;
    } catch {
        return undefined;
    }
}

async function acquireGenerationLock(
    lockPath: string,
    metadata: GenerationLockMetadata,
    destination: string
): Promise<LockFileIdentity> {
    try {
        return await createGenerationLock(lockPath, metadata);
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== 'EEXIST') {
            throw new Error(`Could not create a snapshot lock in ${destination}: ${errorMessage(error)}`);
        }
    }

    let existing: InspectedGenerationLock;
    try {
        existing = await readGenerationLock(lockPath);
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
            return retryGenerationLock(lockPath, metadata, destination);
        }
        throw orphanedGenerationLockError(lockPath, errorMessage(error));
    }

    if (!isProcessConfirmedDead(existing.metadata.pid)) {
        throw generationDestinationInUseError(lockPath);
    }

    // Serialize stale-lock recovery so two extension hosts cannot both inspect
    // the old lock and have one remove the other's newly acquired lock.
    const recoveryLockPath = `${lockPath}.recovery`;
    const recoveryMetadata: GenerationLockMetadata = {
        version: 1,
        pid: process.pid,
        workspaceId: metadata.workspaceId,
        token: crypto.randomUUID(),
        createdAt: Date.now()
    };
    let recoveryIdentity: LockFileIdentity;
    try {
        recoveryIdentity = await createGenerationLock(recoveryLockPath, recoveryMetadata);
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'EEXIST') {
            throw orphanedGenerationLockError(recoveryLockPath, 'another recovery is in progress or its recovery lock is orphaned');
        }
        throw orphanedGenerationLockError(recoveryLockPath, errorMessage(error));
    }

    try {
        let recovery: 'removed' | 'missing' | 'changed' | 'active';
        try {
            recovery = await removeVerifiedStaleGenerationLock(lockPath, existing);
        } catch (error) {
            throw orphanedGenerationLockError(lockPath, errorMessage(error));
        }
        if (recovery === 'changed' || recovery === 'active') {
            throw generationDestinationInUseError(lockPath);
        }

        // Only one retry is allowed. If a competing generator wins after stale-lock
        // removal, exclusive creation fails and its lock remains untouched.
        return await retryGenerationLock(lockPath, metadata, destination);
    } finally {
        await releaseGenerationLock(recoveryLockPath, recoveryMetadata, recoveryIdentity);
    }
}

async function retryGenerationLock(
    lockPath: string,
    metadata: GenerationLockMetadata,
    destination: string
): Promise<LockFileIdentity> {
    try {
        return await createGenerationLock(lockPath, metadata);
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'EEXIST') {
            throw generationDestinationInUseError(lockPath);
        }
        throw new Error(`Could not create a snapshot lock in ${destination}: ${errorMessage(error)}`);
    }
}

async function createGenerationLock(lockPath: string, metadata: GenerationLockMetadata): Promise<LockFileIdentity> {
    const handle = await fs.open(lockPath, 'wx');
    let creationIdentity: LockFileIdentity | undefined;
    let openHandle: typeof handle | undefined = handle;
    try {
        creationIdentity = identityFromStats(await handle.stat());
        await handle.writeFile(JSON.stringify(metadata), 'utf8');
        const writtenIdentity = identityFromStats(await handle.stat());
        if (!sameLockFileObject(creationIdentity, writtenIdentity)) {
            throw new Error('The newly created lock file changed while its metadata was being written.');
        }
        await handle.close();
        openHandle = undefined;

        const writtenLock = await readGenerationLock(lockPath);
        if (!sameLockFileIdentity(writtenIdentity, writtenLock.identity) ||
            !sameGenerationLockMetadata(metadata, writtenLock.metadata)) {
            throw new Error('The newly created lock file changed before it could be verified.');
        }
        return writtenIdentity;
    } catch (error) {
        if (openHandle) {
            try { await openHandle.close(); } catch { /* Continue with identity-checked cleanup. */ }
        }
        if (creationIdentity) await removeNewlyCreatedLockAfterFailure(lockPath, creationIdentity);
        throw new Error(`Could not write snapshot lock at ${lockPath}: ${errorMessage(error)}`);
    }
}

async function readGenerationLock(lockPath: string): Promise<InspectedGenerationLock> {
    const before = await fs.lstat(lockPath);
    if (!before.isFile()) throw new Error('the lock is not a regular file');
    if (before.size > 4096) throw new Error('the lock metadata is larger than expected');
    const beforeIdentity = identityFromStats(before);
    const contents = await fs.readFile(lockPath, 'utf8');
    const after = await fs.lstat(lockPath);
    if (!after.isFile()) throw new Error('the lock is not a regular file');
    const afterIdentity = identityFromStats(after);
    if (!sameLockFileIdentity(beforeIdentity, afterIdentity)) {
        throw new Error('the lock changed while its metadata was being read');
    }
    return { metadata: parseGenerationLockMetadata(contents), identity: afterIdentity };
}

function parseGenerationLockMetadata(contents: string): GenerationLockMetadata {
    let value: unknown;
    try {
        value = JSON.parse(contents);
    } catch {
        throw new Error('the lock metadata is not valid JSON');
    }
    if (!value || typeof value !== 'object' || Array.isArray(value)) {
        throw new Error('the lock metadata has an unrecognized structure');
    }

    const record = value as Record<string, unknown>;
    const expectedKeys = ['version', 'pid', 'workspaceId', 'token', 'createdAt'];
    const keys = Object.keys(record);
    if (keys.length !== expectedKeys.length || expectedKeys.some(key => !Object.prototype.hasOwnProperty.call(record, key))) {
        throw new Error('the lock metadata has an unrecognized structure');
    }
    if (record.version !== 1 || !Number.isSafeInteger(record.pid) || (record.pid as number) <= 0 ||
        typeof record.workspaceId !== 'string' || !isWorkspaceId(record.workspaceId) ||
        typeof record.token !== 'string' ||
        !/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(record.token) ||
        typeof record.createdAt !== 'number' || !Number.isFinite(record.createdAt) || record.createdAt <= 0) {
        throw new Error('the lock metadata is invalid or incomplete');
    }

    return {
        version: 1,
        pid: record.pid as number,
        workspaceId: record.workspaceId as string,
        token: record.token as string,
        createdAt: record.createdAt as number
    };
}

function isWorkspaceId(value: string): boolean {
    return /^[a-f0-9]{64}$/i.test(value) ||
        /^[a-f0-9]{8}-[a-f0-9]{4}-[1-8][a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/i.test(value);
}

function isProcessConfirmedDead(pid: number): boolean {
    try {
        process.kill(pid, 0);
        return false;
    } catch (error) {
        return (error as NodeJS.ErrnoException).code === 'ESRCH';
    }
}

async function removeVerifiedStaleGenerationLock(
    lockPath: string,
    inspected: InspectedGenerationLock
): Promise<'removed' | 'missing' | 'changed' | 'active'> {
    let current: InspectedGenerationLock;
    try {
        // Re-read both the owner metadata and file identity immediately before recovery.
        current = await readGenerationLock(lockPath);
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') return 'missing';
        return 'changed';
    }
    if (!sameLockFileIdentity(inspected.identity, current.identity) ||
        !sameGenerationLockMetadata(inspected.metadata, current.metadata)) return 'changed';
    if (!isProcessConfirmedDead(current.metadata.pid)) return 'active';

    try {
        await fs.unlink(lockPath);
        return 'removed';
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') return 'missing';
        throw error;
    }
}

async function removeNewlyCreatedLockAfterFailure(lockPath: string, createdIdentity: LockFileIdentity): Promise<void> {
    try {
        const current = await fs.lstat(lockPath);
        if (!current.isFile() || !sameLockFileObject(createdIdentity, identityFromStats(current))) return;
        await fs.unlink(lockPath);
    } catch {
        // Cleanup is best-effort and only removes the regular file created by this operation.
    }
}

async function releaseGenerationLock(
    lockPath: string,
    metadata: GenerationLockMetadata,
    identity: LockFileIdentity
): Promise<void> {
    try {
        // Keep the path and token checks together immediately before unlinking.
        const current = await readGenerationLock(lockPath);
        if (!sameLockFileIdentity(identity, current.identity) ||
            !sameGenerationLockMetadata(metadata, current.metadata)) return;
        await fs.unlink(lockPath);
    } catch {
        // Best-effort cleanup after generation; never remove an unverified lock.
    }
}

function identityFromStats(stat: Stats): LockFileIdentity {
    return {
        dev: stat.dev,
        ino: stat.ino,
        size: stat.size,
        birthtimeMs: stat.birthtimeMs,
        ctimeMs: stat.ctimeMs,
        mtimeMs: stat.mtimeMs
    };
}

function sameLockFileObject(first: LockFileIdentity, second: LockFileIdentity): boolean {
    if (first.ino !== 0 || second.ino !== 0) return first.dev === second.dev && first.ino === second.ino;
    return first.dev === second.dev && first.birthtimeMs === second.birthtimeMs;
}

function sameLockFileIdentity(first: LockFileIdentity, second: LockFileIdentity): boolean {
    return sameLockFileObject(first, second) && first.size === second.size &&
        first.birthtimeMs === second.birthtimeMs && first.ctimeMs === second.ctimeMs && first.mtimeMs === second.mtimeMs;
}

function sameGenerationLockMetadata(first: GenerationLockMetadata, second: GenerationLockMetadata): boolean {
    return first.version === second.version && first.pid === second.pid &&
        first.workspaceId === second.workspaceId && first.token === second.token && first.createdAt === second.createdAt;
}

function generationDestinationInUseError(lockPath: string): Error {
    return new Error(`The snapshot destination is currently in use (lock file: ${lockPath}).`);
}

function orphanedGenerationLockError(lockPath: string, reason: string): Error {
    return new Error(
        `Cannot safely recover the snapshot lock at ${lockPath}: ${reason}. Close other active Code Parcel extension instances, then manually remove this orphaned lock file if no generation is running.`
    );
}

function hasBinarySignature(bytes: Buffer): boolean {
    const ascii = bytes.subarray(0, 16).toString('ascii');
    return (bytes.length >= 8 && bytes.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) ||
        (bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) ||
        ascii.startsWith('GIF8') || ascii.startsWith('%PDF-') || ascii.startsWith('PK\x03\x04') ||
        (bytes[0] === 0x1f && bytes[1] === 0x8b) || ascii.startsWith('\x7fELF') ||
        (ascii.startsWith('RIFF') && bytes.subarray(8, 12).toString('ascii') === 'WEBP') ||
        ascii.startsWith('SQLite format 3') || ascii.startsWith('wOFF') || ascii.startsWith('wOF2') ||
        (bytes.length >= 14 && bytes[0] === 0x42 && bytes[1] === 0x4d) ||
        (bytes.length >= 10 && ascii.startsWith('ID3') && bytes[3] <= 4);
}

function buildMarkdown(projectName: string, ownerId: string, files: IncludedFile[], skipped: SkippedFile[]): string {
    let markdown = [
        GENERATOR_MARKER,
        `<!-- Code Parcel workspace-id: ${ownerId} -->`,
        '',
        '# Code Parcel Snapshot',
        '',
        `Project: ${projectName}`,
        `Generated: ${new Date().toISOString()}`,
        `Included files: ${files.length}`,
        '',
        '## Project Structure',
        '',
        ...renderProjectStructure(projectName, files),
        '',
        '## File Contents'
    ].join('\n');
    const sections = files.map(buildFileSection);
    if (sections.length) markdown += `\n\n${sections.join('\n\n')}`;
    if (skipped.length) {
        markdown += `\n\n## Skipped Files\n\n${skipped.map(file =>
            `- ${escapeMarkdownPath(file.relativePath)} \u2014 ${file.reason}`
        ).join('\n')}`;
    }
    return `${markdown}\n`;
}

function buildFileSection(file: IncludedFile): string {
    const fence = '`'.repeat(Math.max(3, longestBacktickRun(file.content) + 1));
    const terminalLineEnding = file.content.endsWith('\n') || file.content.endsWith('\r');
    const closingSeparator = !file.content.length || terminalLineEnding ? '' : '\n';
    const codeBlock = `${fence}${file.language}\n${file.content}${closingSeparator}${fence}`;
    return `### FILE: ${escapeMarkdownPath(file.relativePath)}\n\n${codeBlock}`;
}

function estimateIncludedFileBytes(file: IncludedFile, hasPreviousFile: boolean, directories: Set<string>): number {
    const segments = file.relativePath.split('/');
    let structureBytes = 0;
    for (let index = 0; index < segments.length - 1; index++) {
        const directory = segments.slice(0, index + 1).join('/');
        if (directories.has(directory)) continue;
        directories.add(directory);
        structureBytes += Buffer.byteLength(segments[index], 'utf8') + 1 + 10 + index * 7;
    }
    structureBytes += Buffer.byteLength(segments[segments.length - 1], 'utf8') + 10 + (segments.length - 1) * 7;

    const fenceLength = Math.max(3, longestBacktickRun(file.content) + 1);
    const terminalLineEnding = file.content.endsWith('\n') || file.content.endsWith('\r');
    const closingSeparatorLength = !file.content.length || terminalLineEnding ? 0 : 1;
    const sectionBytes = Buffer.byteLength(`### FILE: ${escapeMarkdownPath(file.relativePath)}\n\n`, 'utf8') +
        fenceLength + Buffer.byteLength(file.language, 'utf8') + 1 + Buffer.byteLength(file.content, 'utf8') +
        closingSeparatorLength + fenceLength + (hasPreviousFile ? 2 : 0);
    return structureBytes + sectionBytes;
}

function assertSnapshotSize(sizeBytes: number): void {
    if (sizeBytes > MAX_SNAPSHOT_SIZE_BYTES) {
        throw new Error('The snapshot exceeds the 50 MiB total size limit. Exclude some files or reduce their size, then generate it again.');
    }
}

interface StructureNode {
    directories: Map<string, StructureNode>;
    files: string[];
}

function renderProjectStructure(projectName: string, files: IncludedFile[]): string[] {
    const root: StructureNode = { directories: new Map(), files: [] };
    for (const file of files) {
        const segments = file.relativePath.split('/');
        let node = root;
        for (const directory of segments.slice(0, -1)) {
            let child = node.directories.get(directory);
            if (!child) {
                child = { directories: new Map(), files: [] };
                node.directories.set(directory, child);
            }
            node = child;
        }
        node.files.push(segments[segments.length - 1]);
    }
    const output = [`${projectName}/`];
    const renderChildren = (node: StructureNode, prefix: string): void => {
        const children: Array<{ name: string; directory: boolean; node?: StructureNode }> = [
            ...[...node.directories.entries()].map(([name, child]) => ({ name, directory: true, node: child })),
            ...node.files.map(name => ({ name, directory: false }))
        ].sort((a, b) => Number(b.directory) - Number(a.directory) || compareNames(a.name, b.name));
        children.forEach((child, index) => {
            const last = index === children.length - 1;
            output.push(`${prefix}${last ? '\u2514\u2500\u2500 ' : '\u251c\u2500\u2500 '}${child.name}${child.directory ? '/' : ''}`);
            if (child.directory && child.node) renderChildren(child.node, `${prefix}${last ? '    ' : '\u2502   '}`);
        });
    };
    renderChildren(root, '');
    return output;
}

function compareNames(a: string, b: string): number {
    const lowerA = a.toLowerCase();
    const lowerB = b.toLowerCase();
    return lowerA < lowerB ? -1 : lowerA > lowerB ? 1 : a < b ? -1 : a > b ? 1 : 0;
}

function compareRelativePaths(a: string, b: string): number {
    const left = a.split('/');
    const right = b.split('/');
    const commonLength = Math.min(left.length, right.length);
    for (let index = 0; index < commonLength; index++) {
        const leftIsDirectory = index < left.length - 1;
        const rightIsDirectory = index < right.length - 1;
        if (leftIsDirectory !== rightIsDirectory) return leftIsDirectory ? -1 : 1;
        const comparison = compareNames(left[index], right[index]);
        if (comparison) return comparison;
    }
    return left.length - right.length;
}

function longestBacktickRun(content: string): number {
    let longest = 0;
    for (const match of content.matchAll(/`+/g)) longest = Math.max(longest, match[0].length);
    return longest;
}

function escapeMarkdownPath(relativePath: string): string {
    return relativePath.replace(/([\\`*_{}\[\]()#+.!<>|])/g, '\\$1');
}

async function assertSafeExistingOutput(outputPath: string, ownerId: string): Promise<void> {
    let stat;
    try {
        stat = await fs.lstat(outputPath);
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') return;
        throw error;
    }
    if (!stat.isFile() || stat.isSymbolicLink()) {
        throw new Error('The configured output path exists and is not a regular Code Parcel file.');
    }
    const handle = await fs.open(outputPath, 'r');
    try {
        const prefix = Buffer.alloc(4096);
        const { bytesRead } = await handle.read(prefix, 0, prefix.length, 0);
        const contents = prefix.subarray(0, bytesRead).toString('utf8');
        if (!contents.startsWith(GENERATOR_MARKER)) {
            throw new Error('The configured output already exists and is not marked as a Code Parcel snapshot.');
        }
        const ownerLine = contents.match(/^<!-- Code Parcel workspace-id: ([a-f0-9]{64}|[a-f0-9]{8}-[a-f0-9]{4}-[1-8][a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}) -->$/im);
        if (contents.includes('Code Parcel workspace-id:') && !ownerLine) {
            throw new Error('The existing snapshot has unreadable workspace ownership metadata and cannot be replaced safely.');
        }
        if (!ownerLine) {
            throw new Error('The existing snapshot has no workspace ownership metadata, so it cannot be replaced safely.');
        }
        if (ownerLine[1] !== ownerId) {
            throw new Error('The destination contains a Code Parcel file owned by another workspace. Choose another filename or folder.');
        }
    } finally {
        await handle.close();
    }
}

async function validateDestinationDirectory(destination: string): Promise<void> {
    let stat;
    try {
        stat = await fs.stat(destination);
    } catch (error) {
        throw new Error(`The configured snapshot folder is unavailable: ${destination} (${errorMessage(error)}).`);
    }
    if (!stat.isDirectory()) throw new Error(`The configured snapshot destination is not a folder: ${destination}`);
    try {
        await fs.access(destination, fsConstants.W_OK);
    } catch (error) {
        throw new Error(`The configured snapshot folder is not writable: ${destination} (${errorMessage(error)}).`);
    }
}

function errorMessage(error: unknown): string {
    return error instanceof Error ? error.message : String(error);
}
